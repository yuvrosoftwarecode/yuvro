#!/bin/bash
# Deploy all applications to single AWS EC2 instance (Production)
# Usage: bash infra/scripts/prod_ec2/deploy-all.sh [branch]
# Deploys all apps via docker-compose.prod.yml

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/../../.." && pwd)"
BRANCH="${1:-main}"
DEPLOY_ENV="${DEPLOY_ENV:-prod}"
DEPLOY_INFRA_TYPE="${DEPLOY_INFRA_TYPE:-ec2}"
COMPOSE_FILE="$PROJECT_ROOT/docker-compose.prod.yml"

echo "🚀 Deploying all Yuvro applications to single EC2 instance (production)..."
echo "   Branch: $BRANCH"
echo "   Environment: $DEPLOY_ENV"
echo "   Infrastructure: $DEPLOY_INFRA_TYPE"
echo "   Compose File: docker-compose.prod.yml"
echo ""

cd "$PROJECT_ROOT"

if [ ! -f "$COMPOSE_FILE" ]; then
  echo "❌ Error: Docker Compose file not found: $COMPOSE_FILE"
  exit 1
fi

echo "✅ All applications EC2 deployment ready!"
echo ""
echo "📋 Step-by-step deployment instructions:"
echo ""
echo "1️⃣  Retrieve EC2 instance information from Terraform:"
echo "   cd $PROJECT_ROOT/infra/opentofu/prod_ec2"
echo "   terraform output ec2_elastic_ips"
echo "   terraform output ec2_ssh_commands"
echo ""
echo "2️⃣  Copy repository to EC2 instance:"
echo "   scp -r -i /path/to/ec2-key.pem $PROJECT_ROOT ubuntu@<EC2_IP>:/home/ubuntu/"
echo ""
echo "3️⃣  SSH into EC2 instance:"
echo "   ssh -i /path/to/ec2-key.pem ubuntu@<EC2_IP>"
echo ""
echo "4️⃣  On EC2 instance, navigate to repo and login to GHCR:"
echo "   cd ~/yuvro"
echo "   echo \$GITHUB_TOKEN | docker login ghcr.io -u USERNAME --password-stdin"
echo ""
echo "5️⃣  On EC2 instance, deploy all services with Docker Compose:"
echo "   DEPLOY_BRANCH=$BRANCH docker-compose -f docker-compose.prod.yml up -d"
echo ""
echo "6️⃣  Verify all services are running:"
echo "   docker-compose -f docker-compose.prod.yml ps"
echo ""
echo "7️⃣  View logs (follow mode):"
echo "   docker-compose -f docker-compose.prod.yml logs -f"
echo ""
echo "📚 Service endpoints on EC2:"
echo "   YCode Backend:       http://<EC2_IP>:8000/api/"
echo "   YCode Frontend:      http://<EC2_IP>:3000"
echo "   YCampus Backend:     http://<EC2_IP>:8001/api/"
echo "   YCampus Frontend:    http://<EC2_IP>:3001"
echo "   YLabs Backend:       http://<EC2_IP>:8002/api/"
echo "   YLabs Frontend:      http://<EC2_IP>:3002"
echo "   YHub Backend:        http://<EC2_IP>:8003/api/"
echo "   YMarketplace Backend: http://<EC2_IP>:8004/api/"
echo "   YMarketplace Frontend: http://<EC2_IP>:3004"
echo "   Code Executor:       http://<EC2_IP>:8009/health"
echo ""
echo "🔄 Common operations on EC2:"
echo "   # Stop all services"
echo "   docker-compose -f docker-compose.prod.yml down"
echo ""
echo "   # View specific service logs"
echo "   docker-compose -f docker-compose.prod.yml logs ycode-backend -f"
echo ""
echo "   # Restart specific service"
echo "   docker-compose -f docker-compose.prod.yml restart ycode-backend"
echo ""
echo "   # Redeploy with new images (pull latest)"
echo "   docker-compose -f docker-compose.prod.yml pull"
echo "   docker-compose -f docker-compose.prod.yml up -d"
echo ""
echo "📄 Single Docker Compose file for all services:"
echo "   $COMPOSE_FILE"
echo ""
echo "💡 Note: All services share a single yuvro-net Docker bridge network"
echo "💡 Database connections use RDS endpoint from .env files"
